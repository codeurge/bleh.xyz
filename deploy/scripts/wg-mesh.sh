#!/usr/bin/env bash
# Configure the WireGuard overlay (interface bleh0) on this host from a
# shared peers file. Every host gets the same file; each finds itself by its
# overlay address.
#
#   sudo deploy/scripts/wg-mesh.sh PEERS_FILE
#
# PEERS_FILE lines (keep it out of the repository; it holds endpoints):
#   <name> <overlay-ip> <public-key> <endpoint host:port or ->
# for example
#   node-a  10.77.0.1   AbC...=  198.51.100.10:51820
#   home    10.77.0.2   DeF...=  -
#   relay-1 10.77.0.11  GhI...=  203.0.113.5:51820
#
# A peer without an endpoint (the home server behind NAT) dials out to the
# others and keeps the tunnel open with PersistentKeepalive. Collect each
# host's public key from `cat /etc/wireguard/bleh0.pub` (printed by
# host-bootstrap.sh). The overlay carries metrics, logs, the reader stream
# between origins and alerting; nothing public.
set -euo pipefail

peers=${1:?usage: wg-mesh.sh PEERS_FILE}
[[ $EUID -eq 0 ]] || { echo "run as root" >&2; exit 77; }
[[ -s /etc/wireguard/bleh0.key ]] || { echo "no /etc/wireguard/bleh0.key; run host-bootstrap.sh first" >&2; exit 1; }
me_pub=$(wg pubkey < /etc/wireguard/bleh0.key)

me_ip=$(awk -v k="$me_pub" '$3 == k {print $2}' "$peers")
[[ -n "$me_ip" ]] || { echo "this host's public key ($me_pub) is not in $peers" >&2; exit 1; }
me_ep=$(awk -v k="$me_pub" '$3 == k {print $4}' "$peers")

umask 077
{
  echo "# Generated by deploy/scripts/wg-mesh.sh from $peers"
  echo "[Interface]"
  echo "Address = $me_ip/24"
  [[ "$me_ep" != "-" ]] && echo "ListenPort = 51820"
  echo "PrivateKey = $(cat /etc/wireguard/bleh0.key)"
  while read -r name ip pub ep; do
    [[ -z "${name:-}" || "$name" == \#* || "$pub" == "$me_pub" ]] && continue
    echo
    echo "# $name"
    echo "[Peer]"
    echo "PublicKey = $pub"
    echo "AllowedIPs = $ip/32"
    [[ "$ep" != "-" ]] && echo "Endpoint = $ep"
    # Keep NAT mappings alive from hosts without a public endpoint.
    [[ "$me_ep" == "-" || "$ep" == "-" ]] && echo "PersistentKeepalive = 25"
  done < "$peers"
} > /etc/wireguard/bleh0.conf

systemctl enable wg-quick@bleh0
systemctl restart wg-quick@bleh0
wg show bleh0
