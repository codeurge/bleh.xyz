// Compiles sol/BlehBlockVerifier.sol with the pinned solc-js (package-lock.json)
// and writes src/bytecode.rs.
//
//   npm ci --ignore-scripts      install the pinned compiler
//   node compile.mjs             regenerate src/bytecode.rs
//   node compile.mjs --check     fail if src/bytecode.rs differs from a fresh build
//
// CI runs the check, so the committed bytecode always matches the source.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = "BlehBlockVerifier.sol";
const CONTRACT = "BlehBlockVerifier";
const SOLC_VERSION = "0.8.38+commit.1835d247";
// Pinned settings. No CBOR metadata, so the bytecode depends only on the code
// (not on comments or file paths); src/bytecode.rs records the source hash.
const SETTINGS = {
  evmVersion: "cancun",
  metadata: { appendCBOR: false, bytecodeHash: "none" },
  optimizer: { enabled: true, runs: 200 },
  viaIR: false,
};

const version = solc.version();
if (!version.startsWith(`${SOLC_VERSION}.`)) {
  console.error(`expected solc ${SOLC_VERSION}, found ${version}; run npm ci --ignore-scripts`);
  process.exit(1);
}

const source = readFileSync(join(here, "sol", SOURCE), "utf8");
const input = {
  language: "Solidity",
  sources: { [SOURCE]: { content: source } },
  settings: {
    ...SETTINGS,
    outputSelection: {
      [SOURCE]: {
        [CONTRACT]: ["evm.bytecode.object", "evm.deployedBytecode.object", "evm.methodIdentifiers"],
      },
    },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const problems = (output.errors ?? []).filter((e) => e.severity !== "info");
for (const e of problems) console.error(e.formattedMessage);
if (problems.length > 0) process.exit(1);

const evm = output.contracts[SOURCE][CONTRACT].evm;
const sha256 = createHash("sha256").update(source).digest("hex");
const methods = Object.entries(evm.methodIdentifiers).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const rust = `//! Generated by \`node compile.mjs\` from \`sol/${SOURCE}\`. Do not edit.

/// Compiler version (solc-js, pinned in \`package-lock.json\`).
pub const SOLC_VERSION: &str = "${SOLC_VERSION}";

/// Compiler settings, as standard-JSON \`settings\` (without \`outputSelection\`).
pub const SOLC_SETTINGS: &str = r#"${JSON.stringify(SETTINGS)}"#;

/// SHA-256 of \`sol/${SOURCE}\`, as lowercase hex.
pub const SOURCE_SHA256: &str = "${sha256}";

/// Creation bytecode of \`${CONTRACT}\`, as hex.
pub const CREATION_CODE: &str = "${evm.bytecode.object}";

/// Runtime bytecode of \`${CONTRACT}\`, as hex.
pub const RUNTIME_CODE: &str = "${evm.deployedBytecode.object}";

/// Function signatures and their 4-byte selectors (hex), from the compiler.
pub const METHOD_IDS: &[(&str, &str)] = &[
${methods.map(([sig, id]) => `    ("${sig}", "${id}"),`).join("\n")}
];
`;

const target = join(here, "src", "bytecode.rs");
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // Missing file: reported below.
  }
  if (current !== rust) {
    console.error("src/bytecode.rs does not match sol/" + SOURCE + "; run: node compile.mjs");
    process.exit(1);
  }
  console.log("src/bytecode.rs matches sol/" + SOURCE + " (solc " + SOLC_VERSION + ")");
} else {
  writeFileSync(target, rust);
  console.log("wrote src/bytecode.rs (solc " + SOLC_VERSION + ")");
}
